#!/usr/bin/env python3
"""Render the example's images as SVG with the standard library only. Run from the repository root:

  python3 examples/supermarket-route/images/make_images.py

  simulation.svg   animated: list-order route vs optimized route on the same store, with time and distance bars
  layouts.svg      the optimized route on eight different store layouts
  benchmark.svg    the Sonnet pair, with and without Herd, on six measures

Routes come from the with-herd solution (with-herd/router.py) on stores generated by verifier/verify_general.py.
"""
import random
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(HERE / "verifier"))
sys.path.insert(0, str(HERE / "with-herd"))
import router  # noqa: E402
import verify_general as vg  # noqa: E402

OUT = HERE / "images"
SHELF, FLOOR, LIST_C, OPT_C, ITEM_C, STATION_C = "#3b4252", "#f7f7f2", "#d08770", "#2e7d32", "#e5a50a", "#1565c0"
FONT = "-apple-system,Segoe UI,Helvetica,Arial,sans-serif"


def solve(canon, ids):
    """Both routes as dicts: cells (x, y) from the start, breakpoints (seconds, path fraction), time and distance."""
    m = {"grid": [list(r) for r in canon["grid"]], "start": canon["station"],
         "products": [{"id": p, "name": v["name"], "pos": v["access"][0]} for p, v in canon["products"].items()]}
    store = router.Store(m)
    out = {}
    for label, order in (("list", ids), ("opt", router.optimize(store, ids))):
        events = list(router.simulate(store, order))
        cells = [(store.start[1], store.start[0])] + [(e["cell"][1], e["cell"][0]) for e in events if e["kind"] == "move"]
        n = max(1, len(cells) - 1)
        pts, moves = [(0.0, 0.0)], 0
        for e in events:
            if e["kind"] == "move":
                moves += 1
            elif e["kind"] == "pick":
                pts += [(e["time"] - router.PICK_S, moves / n), (e["time"], moves / n)]
        end = events[-1]
        out[label] = {"cells": cells, "pts": pts + [(end["time"], 1.0)], "time_s": end["time"], "distance_m": end["dist"]}
    return out


def shelf_rects(rows, px, ox, oy):
    out = []
    for r, row in enumerate(rows):
        c = 0
        while c < len(row):
            if row[c] == "#":
                s = c
                while c < len(row) and row[c] == "#":
                    c += 1
                out.append(f'<rect x="{ox + s * px}" y="{oy + r * px}" width="{(c - s) * px}" height="{px}"/>')
            else:
                c += 1
    return "".join(out)


def polyline(cells, px, ox, oy):
    pts = [(ox + (x + .5) * px, oy + (y + .5) * px) for x, y in cells]
    d, run = [f"M{pts[0][0]:.1f} {pts[0][1]:.1f}"], None
    for a, b in zip(pts, pts[1:]):
        dirn = (round(b[0] - a[0], 3), round(b[1] - a[1], 3))
        if dirn != run and run is not None:
            d.append(f"L{a[0]:.1f} {a[1]:.1f}")
        run = dirn
    d.append(f"L{pts[-1][0]:.1f} {pts[-1][1]:.1f}")
    return " ".join(d)


def dots(canon, ids, px, ox, oy, r):
    out = []
    for p in ids:
        sr, sc = canon["products"][p]["shelf"]
        out.append(f'<circle cx="{ox + (sc + .5) * px}" cy="{oy + (sr + .5) * px}" r="{r}" fill="{ITEM_C}" stroke="#fff" stroke-width="1"/>')
    return "".join(out)


def animated_panel(canon, ids, route, px, ox, oy, color, label, total_s, dist_max, dur):
    w, h = len(canon["grid"][0]), len(canon["grid"])
    d = polyline(route["cells"], px, ox, oy)
    length = (len(route["cells"]) - 1) * px
    pts = route["pts"] + [(total_s * 1.08, 1.0)]
    scale = pts[-1][0]
    keytimes = ";".join(f"{t / scale:.5f}" for t, _ in pts)
    offsets = ";".join(f"{length * (1 - f):.1f}" for _, f in pts)
    keypoints = ";".join(f"{f:.5f}" for _, f in pts)
    widths = ";".join(f"{min(t, route['time_s']) / total_s * (w * px):.1f}" for t, _ in pts)
    dist_w = ";".join(f"{f * route['distance_m'] / dist_max * (w * px):.1f}" for _, f in pts)
    bar_y = oy + h * px + 14
    start = route["cells"][0]
    return f'''
<rect x="{ox}" y="{oy}" width="{w * px}" height="{h * px}" fill="{FLOOR}" stroke="#999"/>
<g fill="{SHELF}" shape-rendering="crispEdges">{shelf_rects(canon["grid"], px, ox, oy)}</g>
<path d="{d}" fill="none" stroke="{color}" stroke-width="2" stroke-linejoin="round" stroke-dasharray="{length:.1f}" stroke-dashoffset="{length:.1f}" opacity=".85">
  <animate attributeName="stroke-dashoffset" values="{offsets}" keyTimes="{keytimes}" dur="{dur}s" repeatCount="indefinite"/>
</path>
{dots(canon, ids, px, ox, oy, 3.2)}
<rect x="{ox + start[0] * px}" y="{oy + start[1] * px}" width="{px}" height="{px}" fill="{STATION_C}"/>
<circle r="5" fill="{color}" stroke="#fff" stroke-width="1.5">
  <animateMotion path="{d}" keyPoints="{keypoints}" keyTimes="{keytimes}" calcMode="linear" dur="{dur}s" repeatCount="indefinite"/>
</circle>
<text x="{ox}" y="{oy - 12}" font-size="15" font-weight="bold" fill="#222">{label}</text>
<text x="{ox + 4}" y="{bar_y}" font-size="11" fill="#555">time-to-prepare-basket</text>
<rect x="{ox}" y="{bar_y + 4}" width="{w * px}" height="9" fill="#e4e4e4"/>
<rect x="{ox}" y="{bar_y + 4}" height="9" fill="{color}" width="0"><animate attributeName="width" values="{widths}" keyTimes="{keytimes}" dur="{dur}s" repeatCount="indefinite"/></rect>
<text x="{ox + 4}" y="{bar_y + 30}" font-size="11" fill="#555">distance-covered</text>
<rect x="{ox}" y="{bar_y + 34}" width="{w * px}" height="9" fill="#e4e4e4"/>
<rect x="{ox}" y="{bar_y + 34}" height="9" fill="{color}" width="0"><animate attributeName="width" values="{dist_w}" keyTimes="{keytimes}" dur="{dur}s" repeatCount="indefinite"/></rect>
<text x="{ox}" y="{bar_y + 62}" font-size="13" fill="#222">{route["time_s"]:.0f} s to prepare the basket, {route["distance_m"]:.0f} m walked</text>
'''


def simulation_svg():
    canon = vg.make_instance("parallel", "S", 7000)
    ids = random.Random(11).sample(sorted(canon["products"]), 14)
    res = solve(canon, ids)
    lr, orr = res["list"], res["opt"]
    px, gap, ox, oy = 8, 40, 20, 92
    w, h = len(canon["grid"][0]) * px, len(canon["grid"]) * px
    saved = 1 - orr["time_s"] / lr["time_s"]
    width, height = ox * 2 + 2 * w + gap, oy + h + 118
    body = (animated_panel(canon, ids, lr, px, ox, oy, LIST_C, "Shopping-list order (not optimized)", lr["time_s"], lr["distance_m"], 26)
            + animated_panel(canon, ids, orr, px, ox + w + gap, oy, OPT_C, "Optimized route", lr["time_s"], lr["distance_m"], 26))
    svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" font-family="{FONT}">
<rect width="100%" height="100%" fill="#ffffff"/>
<text x="{ox}" y="26" font-size="18" font-weight="bold" fill="#111">One basket, two routes: {saved:.0%} less time to prepare it</text>
<text x="{ox}" y="46" font-size="12" fill="#555">14 items on a 60x40 store. Dark blocks are shelves, yellow dots are the items, the blue square is the packing station.</text>
<text x="{ox}" y="63" font-size="12" fill="#555">Both runs use the same walking speed and pick time, and play at the same pace: the shorter route finishes first.</text>
{body}
</svg>
'''
    (OUT / "simulation.svg").write_text(svg)
    return saved


def layouts_svg():
    names = list(vg.FAMILIES)
    px, tw, th, pad = 4, 60 * 4, 40 * 4, 16
    cols = 4
    rows = (len(names) + cols - 1) // cols
    width, height = pad + cols * (tw + pad), 56 + rows * (th + 46)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" font-family="{FONT}">',
             '<rect width="100%" height="100%" fill="#fff"/>',
             f'<text x="{pad}" y="26" font-size="18" font-weight="bold" fill="#111">The same optimizer on eight store layouts</text>',
             f'<text x="{pad}" y="44" font-size="12" fill="#555">Green line: optimized route for 12 items. Each layout was generated, not drawn by hand.</text>']
    for n, fam in enumerate(names):
        c = vg.make_instance(fam, "S", 7000)
        ids = random.Random(n).sample(sorted(c["products"]), 12)
        res = solve(c, ids)
        route, base = res["opt"], res["list"]
        ox, oy = pad + (n % cols) * (tw + pad), 60 + (n // cols) * (th + 46)
        saved = 1 - route["time_s"] / base["time_s"]
        start = route["cells"][0]
        parts.append(f'<rect x="{ox}" y="{oy}" width="{tw}" height="{th}" fill="{FLOOR}" stroke="#999"/>'
                     f'<g fill="{SHELF}" shape-rendering="crispEdges">{shelf_rects(c["grid"], px, ox, oy)}</g>'
                     f'<path d="{polyline(route["cells"], px, ox, oy)}" fill="none" stroke="{OPT_C}" stroke-width="1.3" opacity=".9"/>'
                     f'{dots(c, ids, px, ox, oy, 2.4)}'
                     f'<rect x="{ox + start[0] * px}" y="{oy + start[1] * px}" width="{px * 1.6}" height="{px * 1.6}" fill="{STATION_C}"/>'
                     f'<text x="{ox}" y="{oy + th + 15}" font-size="13" font-weight="bold" fill="#222">{fam}</text>'
                     f'<text x="{ox}" y="{oy + th + 30}" font-size="11" fill="#555">{route["distance_m"]:.0f} m, {saved:.0%} less time than list order</text>')
    parts.append("</svg>")
    (OUT / "layouts.svg").write_text("\n".join(parts))


# measured values, see BENCHMARK.md and results/: (label, with Herd, without Herd, unit, scale label)
ROWS = [("Stores solved with a valid route (of 48)", 48, 38, ""),
        ("Bad-input scenarios handled (of 6)", 6, 4, ""),
        ("Test lines written", 119, 20, ""),
        ("Time to finish", 3.3, 1.05, " min"),
        ("Tokens used", 87, 73, "k")]


def benchmark_svg():
    left, bar_w, row_h = 300, 360, 52
    width, height = left + bar_w + 120, 90 + len(ROWS) * row_h + 70
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" font-family="{FONT}">',
             '<rect width="100%" height="100%" fill="#fff"/>',
             '<text x="16" y="28" font-size="18" font-weight="bold" fill="#111">Same prompt, same model (Sonnet), with and without Herd</text>',
             '<text x="16" y="48" font-size="12" fill="#555">Each pair of bars is scaled to its larger value. One run per arm.</text>']
    for i, (label, herd, plain, unit) in enumerate(ROWS):
        y = 74 + i * row_h
        top = max(herd, plain)
        fmt = (lambda v: f"{v:g}{unit}")
        parts.append(f'<text x="16" y="{y + 21}" font-size="13" fill="#222">{label}</text>')
        for k, (val, color) in enumerate(((herd, OPT_C), (plain, LIST_C))):
            by = y + k * 21
            parts.append(f'<rect x="{left}" y="{by}" width="{max(2, val / top * bar_w):.0f}" height="17" rx="2" fill="{color}"/>'
                         f'<text x="{left + max(2, val / top * bar_w) + 8:.0f}" y="{by + 13}" font-size="12" fill="#222">{fmt(val)}</text>')
    y = 74 + len(ROWS) * row_h + 8
    parts.append(f'<rect x="16" y="{y}" width="12" height="12" fill="{OPT_C}"/><text x="34" y="{y + 11}" font-size="12" fill="#222">with Herd</text>'
                 f'<rect x="120" y="{y}" width="12" height="12" fill="{LIST_C}"/><text x="138" y="{y + 11}" font-size="12" fill="#222">without Herd</text>')
    parts.append(f'<text x="16" y="{y + 36}" font-size="11" fill="#666">Both runs were clean subagents. The Herd run followed the skills and ran the real CLI; no hooks, no reviewer.</text>')
    parts.append("</svg>")
    (OUT / "benchmark.svg").write_text("\n".join(parts))


if __name__ == "__main__":
    saved = simulation_svg()
    layouts_svg()
    benchmark_svg()
    print(f"wrote simulation.svg ({saved:.1%} saved on the animated basket), layouts.svg, benchmark.svg")
